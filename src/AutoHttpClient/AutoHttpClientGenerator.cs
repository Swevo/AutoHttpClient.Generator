                    return true;
                case "AutoHttpClient.PatchAttribute":
                    verb = HttpVerb.Patch;
                    template = attribute.ConstructorArguments[0].Value as string;
                    return true;
            }
        }

        verb = default;
        template = null;
        return false;
    }

