    private static PartContentKind ClassifyPartContent(ITypeSymbol type, INamedTypeSymbol? streamType)
    {
        if (type.SpecialType == SpecialType.System_String)
        {
            return PartContentKind.String;
        }

        if (type is IArrayTypeSymbol { ElementType.SpecialType: SpecialType.System_Byte })
        {
            return PartContentKind.ByteArray;
        }

        if (streamType is not null && InheritsFromOrEquals(type, streamType))
        {
            return PartContentKind.Stream;
        }

        return PartContentKind.Json;
    }

    private static bool InheritsFromOrEquals(ITypeSymbol type, INamedTypeSymbol target)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            if (SymbolEqualityComparer.Default.Equals(current, target))
            {
                return true;
            }
        }

        return false;
    }

    private static bool IsQueryCollectionType(ITypeSymbol type, INamedTypeSymbol? enumerableOfT)
    {
        if (type.SpecialType == SpecialType.System_String || enumerableOfT is null)
        {
            return false;
        }

        if (type is IArrayTypeSymbol)
        {
            return true;
        }

        if (type is INamedTypeSymbol named && named.IsGenericType && SymbolEqualityComparer.Default.Equals(named.OriginalDefinition, enumerableOfT))
        {
            return true;
        }

        return type.AllInterfaces.Any(i => i.IsGenericType && SymbolEqualityComparer.Default.Equals(i.OriginalDefinition, enumerableOfT));
    }

